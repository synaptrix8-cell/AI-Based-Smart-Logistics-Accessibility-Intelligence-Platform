/**
 * Client-Side Dijkstra Router - Computes shortest vs risk-penalized safe route
 * with high-density road-following curves and dynamic blockage avoidance.
 */
export function computeClientSafeRoute(
  originCoords: [number, number], // [lat, lng]
  destCoords: [number, number],   // [lat, lng]
  avoidRiskAbove: number = 0.75,
  blockedSegmentIds: string[] = []
) {
  const avoidRiskThreshold = avoidRiskAbove;
  // Extract all points and create an adjacency graph
  type NodeKey = string;
  const nodeKey = (p: [number, number]): NodeKey => `${p[0].toFixed(4)},${p[1].toFixed(4)}`;
  const keyToPoint = (k: NodeKey): [number, number] => {
    const [lat, lng] = k.split(",").map(Number);
    return [lat, lng];
  };

  interface Edge {
    to: NodeKey;
    distance: number;
    risk: number;
    name: string;
    isBlocked?: boolean;
  }

  const adj: Map<NodeKey, Edge[]> = new Map();

  const addEdge = (
    u: [number, number],
    v: [number, number],
    dist: number,
    risk: number,
    name: string,
    isBlocked: boolean = false
  ) => {
    const ku = nodeKey(u);
    const kv = nodeKey(v);
    if (!adj.has(ku)) adj.set(ku, []);
    if (!adj.has(kv)) adj.set(kv, []);
    adj.get(ku)!.push({ to: kv, distance: dist, risk, name, isBlocked });
    adj.get(kv)!.push({ to: ku, distance: dist, risk, name, isBlocked });
  };

  // Add road segments to graph
  for (const seg of EAST_KHASI_HILLS_SEGMENTS) {
    const isBlocked = blockedSegmentIds.includes(seg.id);
    const effectiveRisk = isBlocked ? 0.99 : seg.risk_score;
    const coords = seg.coordinates.map((c) => [c[1], c[0]] as [number, number]); // [lat, lng]
    const subDist = seg.length_km / Math.max(1, coords.length - 1);
    for (let i = 0; i < coords.length - 1; i++) {
      addEdge(coords[i], coords[i + 1], subDist, effectiveRisk, seg.name, isBlocked);
    }
  }

  // Connect adjacent road endpoints if within 250m to guarantee connected graph across junctions
  const allNodes = Array.from(adj.keys()).map(keyToPoint);
  for (let i = 0; i < allNodes.length; i++) {
    for (let j = i + 1; j < allNodes.length; j++) {
      const d = haversine(allNodes[i], allNodes[j]);
      if (d > 0 && d <= 0.25) {
        addEdge(allNodes[i], allNodes[j], d, 0.25, "Junction Link", false);
      }
    }
  }

  // Find nearest start and end nodes
  const findNearest = (target: [number, number]): NodeKey => {
    let bestKey = nodeKey(allNodes[0]);
    let minD = Infinity;
    for (const n of allNodes) {
      const d = haversine(target, n);
      if (d < minD) {
        minD = d;
        bestKey = nodeKey(n);
      }
    }
    return bestKey;
  };

  const startKey = findNearest(originCoords);
  const targetKey = findNearest(destCoords);

  const runDijkstra = (useRiskPenalty: boolean) => {
    const distMap: Map<NodeKey, number> = new Map();
    const prevMap: Map<NodeKey, { node: NodeKey; edge: Edge } | null> = new Map();
    const visited: Set<NodeKey> = new Set();

    for (const k of adj.keys()) {
      distMap.set(k, Infinity);
    }
    distMap.set(startKey, 0);

    while (visited.size < distMap.size) {
      let u: NodeKey | null = null;
      let minD = Infinity;
      for (const [k, d] of distMap.entries()) {
        if (!visited.has(k) && d < minD) {
          minD = d;
          u = k;
        }
      }

      if (!u || minD === Infinity || u === targetKey) break;
      visited.add(u);

      const neighbors = adj.get(u) || [];
      for (const edge of neighbors) {
        if (visited.has(edge.to)) continue;

        let weight = edge.distance;
        if (useRiskPenalty) {
          if (edge.isBlocked) {
            weight *= 1000.0; // Extreme blockage avoidance penalty
          } else if (edge.risk > avoidRiskThreshold) {
            // Sector risk exceeds user's safety tolerance threshold!
            // Apply steep exponential penalty proportional to excess risk
            const excessRatio = (edge.risk - avoidRiskThreshold) / Math.max(0.05, 1.0 - avoidRiskThreshold);
            weight *= (12.0 + 45.0 * (excessRatio ** 2));
          } else {
            // Within acceptable tolerance: gentle quadratic cost penalty
            weight *= (1.0 + (edge.risk / Math.max(0.1, avoidRiskThreshold)) ** 2);
          }
        }

        const alt = distMap.get(u)! + weight;
        if (alt < distMap.get(edge.to)!) {
          distMap.set(edge.to, alt);
          prevMap.set(edge.to, { node: u, edge });
        }
      }
    }

    // Reconstruct path
    const rawPath: [number, number][] = [];
    let curr: NodeKey | null = targetKey;
    let totalKm = 0;
    let riskWeightedSum = 0;
    const corridors = new Set<string>();
    let hasBlockedEdge = false;

    while (curr && prevMap.has(curr)) {
      rawPath.unshift(keyToPoint(curr));
      const step = prevMap.get(curr);
      if (step) {
        totalKm += step.edge.distance;
        riskWeightedSum += step.edge.distance * step.edge.risk;
        if (step.edge.name !== "Junction Link") {
          corridors.add(step.edge.name);
        }
        if (step.edge.isBlocked) {
          hasBlockedEdge = true;
        }
        curr = step.node;
      } else {
        break;
      }
    }

    if (curr) rawPath.unshift(keyToPoint(curr));

    // Make sure origin and destination endpoints are smoothly attached
    if (rawPath.length > 0) {
      if (haversine(originCoords, rawPath[0]) > 0.05) {
        rawPath.unshift(originCoords);
      }
      if (haversine(destCoords, rawPath[rawPath.length - 1]) > 0.05) {
        rawPath.push(destCoords);
      }
    }

    const avgRisk = totalKm > 0 ? Number((riskWeightedSum / totalKm).toFixed(2)) : 0;

    return {
      coordinates: rawPath,
      distance_km: Number(totalKm.toFixed(1)),
      avg_risk: avgRisk,
      corridors: Array.from(corridors),
      hasBlockedEdge,
    };
  };

  const shortest = runDijkstra(false);
  const safe = runDijkstra(true);

  // A route is rerouted if:
  // 1) The shortest path encountered a physical blockage and safe path bypassed it, OR
  // 2) The shortest path's risk exceeds the user's custom avoidRiskThreshold and safe route took a safer corridor!
  const shortestHasExcessRisk = shortest.hasBlockedEdge || shortest.avg_risk > avoidRiskThreshold;
  const isActuallyRerouted = Boolean(
    (shortest.hasBlockedEdge && !safe.hasBlockedEdge) ||
    (shortestHasExcessRisk && safe.avg_risk < shortest.avg_risk && safe.distance_km !== shortest.distance_km)
  );

  const finalSafe = isActuallyRerouted
    ? {
        ...safe,
        is_rerouted: true,
        reroute_reason: shortest.hasBlockedEdge
          ? "Autonomous Reroute: Active hazard bypassed via alternate connected corridor"
          : `Safety Filter Reroute (${(avoidRiskThreshold * 100).toFixed(0)}%): Avoided sector exceeding safety limit in favor of all-weather bypass`,
      }
    : {
        ...shortest,
        is_rerouted: false,
        reroute_reason: undefined,
      };

  const riskReduction = isActuallyRerouted
    ? Math.max(
        0,
        Math.round(((shortest.avg_risk - safe.avg_risk) / Math.max(0.01, shortest.avg_risk)) * 100)
      )
    : 0;

  return {
    shortest_route: {
      ...shortest,
      is_rerouted: false,
    },
    safe_route: finalSafe,
    risk_reduction_pct: riskReduction,
  };
}
